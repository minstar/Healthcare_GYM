def concat_sft_files(paths: list[Path], dest: Path) -> int:
    """Concatenate accepted-rollout jsonl files.  Returns the example count."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    n = 0
    with dest.open("w", encoding="utf-8") as out:
        for p in paths:
            if not p.exists():
                continue
            for line in p.read_text(encoding="utf-8").splitlines():
                if line.strip():
                    out.write(line + "\n")
                    n += 1
    return n


def curve_row(it: int, policy: str, gen_stats: dict, heldout: dict,
              n_train_examples: int, init_model: str) -> dict:
    """One row of the curve the rebuttal plots instead of a single endpoint."""
    return {
        "iteration": it,
        "policy_rolled_out": policy,
        "sft_init_from": init_model,
        "acceptance_rate": gen_stats.get("acceptance_rate"),
        "task_coverage": gen_stats.get("task_coverage"),
        "n_rollouts": gen_stats.get("n_rollouts"),
        "n_accepted": gen_stats.get("n_accepted"),
        "n_selected": gen_stats.get("n_selected"),
        "n_train_examples": n_train_examples,
        "threshold_verdict": gen_stats.get("threshold_verdict"),
        "acceptance_if_accepted_on": gen_stats.get("acceptance_if_accepted_on"),
        "heldout": heldout,
        "timestamp": datetime.now().isoformat(),
    }


def heldout_summary(stats: dict) -> dict:
    """The held-out numbers worth carrying into the rebuttal table."""
    dist = stats.get("score_distribution", {})
    def m(k):
        return dist.get(k, {}).get("mean")
    return {
        "n_tasks": stats.get("n_tasks"),
        "qa_accuracy": m("qa_accuracy"),
        "accuracy": m("accuracy"),
        "verl_acc": m("verl_acc"),
        "composite_reward": m("composite_reward"),
        "action_score": m("action_score"),
    }


