def main(argv=None) -> int:
    cfg = cfg_from_args(build_parser().parse_args(argv))
    problems = preflight(cfg)
    for p in problems:
        print(f"[preflight] {p}")
    if problems and not cfg.dry_run:
        return 2
    if cfg.dry_run:
        print(f"DRYRUN base_model={cfg.base_model}")
        print(f"DRYRUN out_root={cfg.out_root}")
        print(f"DRYRUN iterations={cfg.iterations} samples_per_task={cfg.samples_per_task} "
              f"max_turns={cfg.max_turns}")
        print(f"DRYRUN accept_on={cfg.accept_on} threshold="
              f"{cfg.accept_threshold if cfg.accept_threshold is not None else 'default'}")
        print(f"DRYRUN init_from={cfg.init_from} dataset_scope={cfg.dataset_scope} "
              f"sft_source={cfg.sft_source} peft={cfg.peft}")
        print(f"DRYRUN preflight_problems={len(problems)}")
    run_loop(cfg)
    if cfg.dry_run:
        print("DRYRUN ok")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
