@dataclass
class LoopConfig:
    base_model: str = ""
    out_root: str = ""
    iterations: int = 3

    # Generation (mirrors star_generate.GenConfig; kept flat for the CLI)
    pool: str = "full_4modality_clean"
    split: str = "train"
    limit: int = 0
    samples_per_task: int = 3
    temperature: float = 1.0
    max_turns: int = 5
    max_new_tokens: int = 2048
    workers: int = 8
    no_think: bool = True
    seed: int = 42

    # Acceptance
    accept_on: str = "qa_accuracy"
    accept_threshold: Optional[float] = None
    max_accepted_per_task: int = 1
    allow_uninformative: bool = False

    # STaR structure
    init_from: str = "base"           # base | previous
    dataset_scope: str = "current"    # current | accumulated
    sft_source: str = "sft_path"      # sft_path | trajectory_dir

    # SFT
    sft_gpus: int = 7                 # same student topology as the RL arms
    sft_epochs: int = 2
    sft_lr: float = 1e-5
    sft_batch: int = 1
    sft_grad_accum: int = 8
    sft_max_length: int = 8192
    sft_max_samples: int = 200000     # must exceed |D_n| or the trainer silently subsamples
    peft: bool = False                # full-parameter, matching the RL arms
    peft_r: int = 16

    # Serving
    serve_port: int = 31500
    serve_gpus: int = 8
    serve_context: int = 32768
    serve_mem_fraction: float = 0.85
    server_url: Optional[str] = None  # external server; skips serve/stop

    # Held-out probe
    heldout_split: str = "test"
    heldout_size: int = 200
    heldout_temperature: float = 0.1

    dry_run: bool = False
    resume: bool = True


# ══════════════════════════════════════════════════════════════════════
#  Serving
# ══════════════════════════════════════════════════════════════════════


def _server_healthy(url: str, timeout: float = 5.0) -> bool:
    try:
        with urllib.request.urlopen(f"{url}/v1/models", timeout=timeout) as r:
            return r.status == 200
    except Exception:
        return False


class SglangServer:
    """Serve one checkpoint for the generation phase.

    Mirrors ``runs/eval_agentic.slurm``'s launch and liveness check, including
    ``--attention-backend triton``: verl hardcodes ``fa3`` elsewhere on this
    fleet and fa3 raises on Blackwell, so triton is the one that works here.
    """

    def __init__(self, model: str, port: int, gpus: int, log_path: Path,
                 context: int = 32768, mem_fraction: float = 0.85):
        self.model, self.port, self.gpus = model, port, gpus
        self.log_path, self.context, self.mem_fraction = log_path, context, mem_fraction
        self.proc: Optional[subprocess.Popen] = None

    @property
    def url(self) -> str:
        return f"http://127.0.0.1:{self.port}"

    def command(self) -> list[str]:
        return [
            sys.executable, "-m", "sglang.launch_server",
            "--model-path", self.model,
            "--served-model-name", "hcgym",
            "--host", "127.0.0.1", "--port", str(self.port),
            "--trust-remote-code",
            "--context-length", str(self.context),
            "--mem-fraction-static", str(self.mem_fraction),
            "--tp-size", "1",
            # Data parallel across the whole node: generation is the dominant
            # cost of a STaR iteration and star_generate drives the server with
            # --workers concurrent episodes.
            "--dp-size", str(self.gpus),
            "--attention-backend", "triton",
            # The standalone-server equivalent of the RL arms'
            # engine_kwargs.sglang.mm_attention_backend=triton_attn: verl
            # defaults that to "fa3", which raises on Blackwell for any VLM
            # backbone.  Harmless for a text-only backbone (sglang only reads it
            # on the vision path).  The RL arms' other B200 setting,
            # free_cache_engine=False, has no counterpart here: it exists
            # because verl colocates actor and rollout and releases sglang's KV
            # cache through TorchMemorySaver, whose resume writes in place to an
            # inference_mode tensor and dies.  This server is not owned by verl,
            # holds no colocated actor and is never released mid-run, so
            # TorchMemorySaver is not in the picture at all.
            "--mm-attention-backend", "triton_attn",
        ]

    def start(self, wait_s: int = 3000) -> str:
        self.log_path.parent.mkdir(parents=True, exist_ok=True)
        logger.info(f"[star] serving {self.model} on {self.url} ({self.gpus} GPU)")
        with self.log_path.open("w") as lf:
            self.proc = subprocess.Popen(self.command(), stdout=lf, stderr=subprocess.STDOUT,
                                         start_new_session=True)
        t0 = time.time()
        while time.time() - t0 < wait_s:
            if _server_healthy(self.url):
                logger.info(f"[star] server healthy after {time.time() - t0:.0f}s")
                return self.url
            if self.proc.poll() is not None:
                tail = self.log_path.read_text(errors="ignore")[-4000:]
                raise RuntimeError(f"sglang died during startup:\n{tail}")
            time.sleep(10)
        self.stop()
        raise TimeoutError(f"sglang never became healthy within {wait_s}s")

    def stop(self):
        if self.proc and self.proc.poll() is None:
            try:
                os.killpg(os.getpgid(self.proc.pid), signal.SIGTERM)
                self.proc.wait(timeout=120)
            except Exception:
                try:
                    os.killpg(os.getpgid(self.proc.pid), signal.SIGKILL)
                except Exception:
                    pass
        self.proc = None


