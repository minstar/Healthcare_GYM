"""STaR outer loop for the Healthcare AI GYM rebuttal.

REIMPLEMENTATION NOTICE
=======================
Independent reimplementation of STaR (Zelikman, Wu, Mu & Goodman, NeurIPS
2022, arXiv:2203.14465).  ``github.com/ezelikman/STaR`` was NOT run — it is
JAX 0.2.12 / mesh-transformer-jax / GPT-J-6B on TPU + Ray and does not run on
this cluster.  Deviations are enumerated in ``baselines/STAR_PORT.md``.

THE LOOP
========
STaR Algorithm 1, with the paper's two structural choices kept:

    M_0 <- base
    for n in 1..N:
        rollouts <- M_{n-1} over the training pool          (star_generate.py)
        D_n      <- rollouts that passed the acceptance test
        M_n      <- fine_tune(BASE, D_n)                     (sft_trainer.py)

Two details that are easy to get wrong and that the paper is explicit about:

  * ``--init-from base`` (default).  Every iteration fine-tunes the ORIGINAL
    backbone, not the previous iteration's checkpoint.  Zelikman et al. train
    from the original pretrained model each outer loop "to avoid overfitting".
    ``--init-from previous`` gives the continual-training variant.
  * ``--dataset-scope current`` (default).  D_n is the CURRENT iteration's
    accepted set; it is not accumulated across iterations, because the
    rationales are re-generated by the improved policy each time.
    ``--dataset-scope accumulated`` gives the union variant.

Everything the rebuttal needs to plot the curve rather than a single endpoint
is persisted per iteration: acceptance rate, task coverage, dataset size, the
full score distribution, and a held-out score measured with the same GYM loop
every other condition in the paper is measured with.

Usage
-----
    python scripts/rebuttal/star_iterate.py \
        --base-model /path/to/Qwen3.5-9B \
        --out-root   /path/to/hcgym_rebuttal/baselines/STaR/q9b_star \
        --iterations 3 --samples-per-task 3 --max-turns 5 \
        --accept-on qa_accuracy

    python scripts/rebuttal/star_iterate.py ... --dry-run   # print the plan, run nothing
"""

