def generate_command(cfg: LoopConfig, model: str, server_url: str, out_dir: Path,
                     *, split: str, samples: int, temperature: float,
                     eval_only: bool, limit: int) -> list[str]:
    cmd = [
        sys.executable, str(STAR_GENERATE),
        "--model", model,
        "--backend", "sglang",
        "--server-url", server_url,
        "--pool", cfg.pool,
        "--split", split,
        "--samples-per-task", str(samples),
        "--temperature", str(temperature),
        "--top-p", "0.95",
        "--max-new-tokens", str(cfg.max_new_tokens),
        "--max-turns", str(cfg.max_turns),
        "--workers", str(cfg.workers),
        "--seed", str(cfg.seed),
        "--accept-on", cfg.accept_on,
        "--max-accepted-per-task", str(cfg.max_accepted_per_task),
        "--iterations-planned", str(cfg.iterations),
        "--out-dir", str(out_dir),
    ]
    if cfg.accept_threshold is not None:
        cmd += ["--accept-threshold", str(cfg.accept_threshold)]
    if cfg.no_think:
        cmd += ["--no-think"]
    if limit:
        cmd += ["--limit", str(limit)]
    if eval_only:
        # A held-out probe never writes training data and must never stop the
        # loop on a "degenerate acceptance rate" — for the probe that number is
        # the measurement, not a misconfiguration.
        cmd += ["--eval-only", "--no-keep-rejected", "--allow-uninformative"]
    elif cfg.allow_uninformative:
        cmd += ["--allow-uninformative"]
    return cmd


def sft_config_dict(cfg: LoopConfig, init_model: str, data_path: Path,
                    output_dir: Path, run_name: str) -> dict:
    """The YAML ``BioAgentSFTConfig.from_yaml`` consumes.

    Three settings here are load-bearing for the baseline being genuine rather
    than a strawman, and each is argued in STAR_PORT.md:

      qa_tasks_path: ""   The trainer DEFAULTS to
                          data/domains/medical_qa/tasks.json, and
                          ``qa_tasks_to_sft`` synthesises gold-answer
                          demonstrations from it.  Leaving it at the default
                          would silently mix oracle answers into a baseline
                          whose whole point is that it only ever sees its own
                          successful rollouts.  It must be empty.
      peft.enabled: false The RL arms update all parameters.  A LoRA-only STaR
                          arm would lose on capacity, not on method.
      min_reward: 0.0     star_generate has already applied the acceptance
                          test; the trainer's own filter re-reads
                          max(final_reward, action_score), which is a DIFFERENT
                          quantity from the acceptance signal.  Set to 0.0 it
                          is a pass-through over an already-filtered directory.
                          (Only used by the trajectory_dir source.)
    """
    d = {
        "model": {
            "name_or_path": init_model,
            "torch_dtype": "bfloat16",
            # sdpa: this venv has no flash-attn wheel and common_env.sh already
            # pins TRANSFORMERS_ATTN_IMPLEMENTATION=sdpa for every arm.
            "attn_implementation": "sdpa",
        },
        "peft": {
            "enabled": bool(cfg.peft),
            "r": cfg.peft_r,
            "lora_alpha": 2 * cfg.peft_r,
            "lora_dropout": 0.05,
            "target_modules": ["q_proj", "k_proj", "v_proj", "o_proj",
                               "gate_proj", "up_proj", "down_proj"],
        },
        "dataset": {
            "qa_tasks_path": "",
            "instruction_path": "",
            "min_reward": 0.0,
            "max_samples": cfg.sft_max_samples,
            "max_length": cfg.sft_max_length,
            "train_ratio": 0.95,
        },
        "training": {
            "output_dir": str(output_dir),
            "num_train_epochs": cfg.sft_epochs,
            "per_device_train_batch_size": cfg.sft_batch,
            "gradient_accumulation_steps": cfg.sft_grad_accum,
            "learning_rate": cfg.sft_lr,
            "lr_scheduler_type": "cosine",
            "warmup_ratio": 0.1,
            "bf16": True,
            "logging_steps": 5,
            "save_steps": 500,
            "eval_steps": 200,
            "save_total_limit": 1,
            "seed": cfg.seed,
        },
        "logging": {
            "project": "hcgym-rebuttal",
            "run_name": run_name,
            "use_wandb": os.environ.get("WANDB_DISABLED", "") != "true",
        },
    }
    if cfg.sft_source == "trajectory_dir":
        d["dataset"]["trajectory_dir"] = str(data_path)
        d["dataset"]["sft_path"] = ""
    else:
        d["dataset"]["sft_path"] = str(data_path)
        d["dataset"]["trajectory_dir"] = ""
    return d


def sft_command(cfg: LoopConfig, config_path: Path) -> list[str]:
    return [
        "accelerate", "launch",
        "--num_processes", str(cfg.sft_gpus),
        "--mixed_precision", "bf16",
        str(SFT_TRAINER),
        "--config", str(config_path),
    ]


# ══════════════════════════════════════════════════════════════════════
#  Hooks (so the loop is testable with no GPU)
# ══════════════════════════════════════════════════════════════════════


class Hooks:
    """Side effects of one iteration, isolated so tests can replace them."""

    def __init__(self, dry_run: bool = False):
        self.dry_run = dry_run
        self.calls: list[dict] = []

    def _run(self, cmd: list[str], cwd: Path, tag: str):
        self.calls.append({"tag": tag, "cmd": cmd})
        line = " ".join(shlex.quote(c) for c in cmd)
        if self.dry_run:
            print(f"DRYRUN {tag}: {line}")
            return 0
        logger.info(f"[star] {tag}: {line}")
        return subprocess.call(cmd, cwd=str(cwd))

    def serve(self, cfg: LoopConfig, model: str, log_path: Path):
        if cfg.server_url:
            return None, cfg.server_url
        srv = SglangServer(model, cfg.serve_port, cfg.serve_gpus, log_path,
                           cfg.serve_context, cfg.serve_mem_fraction)
        if self.dry_run:
            self.calls.append({"tag": "serve", "cmd": srv.command()})
            print("DRYRUN serve: " + " ".join(shlex.quote(c) for c in srv.command()))
            return None, srv.url
        return srv, srv.start()

    def stop(self, srv):
        if srv is not None:
            srv.stop()

    def generate(self, cmd: list[str], out_dir: Path) -> dict:
        rc = self._run(cmd, HCGYM_ROOT, "generate")
        if self.dry_run:
            return {"acceptance_rate": None, "n_selected": None, "dry_run": True}
        stats_path = out_dir / "gen_stats.json"
        if rc not in (0,) and not stats_path.exists():
            raise RuntimeError(f"star_generate failed (rc={rc}) and wrote no stats")
        stats = json.loads(stats_path.read_text(encoding="utf-8"))
        stats["_returncode"] = rc
        return stats

    def sft(self, cmd: list[str], output_dir: Path) -> str:
        rc = self._run(cmd, HCGYM_ROOT, "sft")
        final = output_dir / "final"
        if self.dry_run:
            return str(final)
        if rc != 0:
            raise RuntimeError(f"SFT failed with rc={rc}")
        if not (final / "config.json").exists():
            raise RuntimeError(f"SFT produced no usable checkpoint at {final}")
        return str(final)


