#  The loop
# ══════════════════════════════════════════════════════════════════════


def run_loop(cfg: LoopConfig, hooks: Optional[Hooks] = None) -> dict:
    hooks = hooks or Hooks(dry_run=cfg.dry_run)
    root = Path(cfg.out_root)
    root.mkdir(parents=True, exist_ok=True)
    (root / "loop_config.json").write_text(
        json.dumps(asdict(cfg), indent=2, default=str), encoding="utf-8")

    curve: list[dict] = []
    curve_path = root / "star_curve.json"
    if cfg.resume and curve_path.exists():
        try:
            curve = json.loads(curve_path.read_text(encoding="utf-8")).get("iterations", [])
        except Exception:
            curve = []

    policy = cfg.base_model
    for it in range(cfg.iterations):
        it_dir = root / f"iter_{it:02d}"
        it_dir.mkdir(parents=True, exist_ok=True)
        state_path = it_dir / "state.json"

        if cfg.resume and state_path.exists():
            st = json.loads(state_path.read_text(encoding="utf-8"))
            if st.get("done"):
                logger.info(f"[star] iteration {it} already complete — resuming past it")
                policy = st["checkpoint"]
                if not any(r["iteration"] == it for r in curve):
                    curve.append(st.get("curve_row", {"iteration": it}))
                continue

        logger.info(f"[star] ===== iteration {it} — rolling out {policy} =====")
        srv, url = hooks.serve(cfg, policy, root / "logs" / f"sglang_iter{it:02d}.log")
        try:
            # Held-out probe of the CURRENT policy, before it is changed.  At
            # it=0 this is the base model's score, which anchors the curve.
            heldout = {}
            if cfg.heldout_size != 0:
                hcmd = generate_command(cfg, policy, url, it_dir / "heldout",
                                        split=cfg.heldout_split, samples=1,
                                        temperature=cfg.heldout_temperature,
                                        eval_only=True, limit=cfg.heldout_size)
                hstats = hooks.generate(hcmd, it_dir / "heldout")
                heldout = heldout_summary(hstats)

            gcmd = generate_command(cfg, policy, url, it_dir / "gen",
                                    split=cfg.split, samples=cfg.samples_per_task,
                                    temperature=cfg.temperature,
                                    eval_only=False, limit=cfg.limit)
            gen_stats = hooks.generate(gcmd, it_dir / "gen")
        finally:
            hooks.stop(srv)

        verdict = gen_stats.get("threshold_verdict")
        if verdict not in (None, "ok") and not cfg.allow_uninformative:
            # At iteration 0 a degenerate acceptance rate means the threshold or
            # the signal is wrong and nothing downstream is interpretable.
            # Later on, a HIGH rate is the expected STaR endgame (the policy has
            # learned to solve the pool) and is a result, not a bug — so it is
            # recorded and the loop continues.
            if it == 0 or verdict in ("empty", "uninformative_zero"):
                raise RuntimeError(
                    f"iteration {it}: acceptance rate is degenerate ({verdict}, "
                    f"{gen_stats.get('acceptance_rate')}). Re-choose --accept-on / "
                    "--accept-threshold, or pass --allow-uninformative to proceed anyway.")
            logger.warning(f"[star] iteration {it}: acceptance verdict={verdict} — recorded, continuing")

        # ── dataset for this iteration ──
        if cfg.sft_source == "trajectory_dir":
            data_path = it_dir / "gen" / "trajectory_dir"
            n_examples = gen_stats.get("n_selected") or 0
        else:
            sources = [root / f"iter_{j:02d}" / "gen" / "star_sft.jsonl"
                       for j in (range(it + 1) if cfg.dataset_scope == "accumulated" else [it])]
            data_path = it_dir / "sft_data.jsonl"
            if hooks.dry_run:
                n_examples = gen_stats.get("n_selected") or 0
            else:
                n_examples = concat_sft_files(sources, data_path)
                if n_examples == 0:
                    raise RuntimeError(
                        f"iteration {it}: no accepted trajectories to train on "
                        f"({[str(s) for s in sources]})")

        # ── SFT ──
        init_model = cfg.base_model if cfg.init_from == "base" else policy
        sft_out = it_dir / "sft"
        cfg_path = it_dir / "sft_config.yaml"
        _write_yaml(sft_config_dict(cfg, init_model, data_path, sft_out,
                                    f"star_iter{it:02d}"), cfg_path)
        checkpoint = hooks.sft(sft_command(cfg, cfg_path), sft_out)

        row = curve_row(it, policy, gen_stats, heldout, n_examples, init_model)
        curve = [r for r in curve if r.get("iteration") != it] + [row]
        curve.sort(key=lambda r: r["iteration"])
        # A dry run must never leave a "done" marker behind: the next REAL run
        # resumes past any iteration whose state.json says done, so writing one
        # here would silently skip training.
        if not hooks.dry_run:
            state_path.write_text(json.dumps(
                {"done": True, "checkpoint": checkpoint, "curve_row": row},
                indent=2, default=str), encoding="utf-8")
            _write_curve(curve_path, cfg, curve)
        policy = checkpoint

    # Final held-out probe of the trained policy, so the last iteration's SFT
    # is represented on the curve rather than only its input.
    final = {}
    if cfg.heldout_size != 0:
        srv, url = hooks.serve(cfg, policy, root / "logs" / "sglang_final.log")
        try:
            hcmd = generate_command(cfg, policy, url, root / "heldout_final",
                                    split=cfg.heldout_split, samples=1,
                                    temperature=cfg.heldout_temperature,
                                    eval_only=True, limit=cfg.heldout_size)
            final = heldout_summary(hooks.generate(hcmd, root / "heldout_final"))
        finally:
            hooks.stop(srv)
    curve.append({"iteration": cfg.iterations, "policy_rolled_out": policy,
                  "heldout": final, "final": True})
    if not hooks.dry_run:
        _write_curve(curve_path, cfg, curve)

    print_curve(curve)
    return {"final_policy": policy, "iterations": curve, "curve_path": str(curve_path)}


def _write_curve(path: Path, cfg: LoopConfig, curve: list[dict]) -> None:
    path.write_text(json.dumps(
        {"config": asdict(cfg), "iterations": curve}, indent=2, default=str),
        encoding="utf-8")


def _write_yaml(d: dict, path: Path) -> None:
    import yaml  # noqa: PLC0415
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump(d, sort_keys=False), encoding="utf-8")


def print_curve(curve: list[dict]) -> None:
    print("=" * 96)
    print("  STaR iteration curve")
    print("=" * 96)
    print(f"  {'it':>3} {'accept':>8} {'cover':>8} {'n_train':>9} "
          f"{'ho_qa_acc':>10} {'ho_verl_acc':>12} {'ho_composite':>13}")
    print("-" * 96)
