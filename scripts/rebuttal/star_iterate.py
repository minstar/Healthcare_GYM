def preflight(cfg: LoopConfig) -> list[str]:
    """Everything that must exist before a real run.  Returns problems."""
    problems = []
    if not cfg.dry_run:
        if not Path(cfg.base_model, "config.json").exists():
            problems.append(f"no config.json under base model {cfg.base_model}")
        try:
            import trl  # noqa: F401,PLC0415
        except Exception:
            problems.append(
                "trl is not importable in this environment — "
                "bioagents/training/sft_trainer.py imports it inside train(). "
                "Install it into the run venv before launching the SFT half "
                "(the generation half does not need it).")
    base = HCGYM_ROOT / "data" / "domains" / cfg.pool
    for f in ("tasks.json", "split_tasks.json"):
        if not (base / f).exists():
            problems.append(f"missing pool file {base / f}")
    if not STAR_GENERATE.exists():
        problems.append(f"missing {STAR_GENERATE}")
    if not SFT_TRAINER.exists():
        problems.append(f"missing {SFT_TRAINER}")
    if cfg.init_from not in ("base", "previous"):
        problems.append(f"--init-from must be base|previous, got {cfg.init_from}")
    if cfg.dataset_scope not in ("current", "accumulated"):
        problems.append(f"--dataset-scope must be current|accumulated, got {cfg.dataset_scope}")
    return problems


